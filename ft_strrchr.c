#include "libft.h"

char *ft_strrchr(const char *s, int c)
{
    int i;
    char *aux;

    i = 0;
    aux = c;
    while (s[i])
    {
        if (s[i] == c)
            aux = &c;
        i++;
    }
    return aux;
}